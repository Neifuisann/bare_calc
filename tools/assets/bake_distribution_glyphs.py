"""Bake the three distribution labels from the pinned OFL math font.

Reuses the pixel-grid rasterizer without changing the frozen math font or
the user's hand-drawn menu chrome font. Run from any directory with fontTools.
"""
from pathlib import Path
from bake_calculator_font import load_font, raster, UNIT, FONT_SHA256


def main():
    font, glyphs, _, _ = load_font()
    cmap = font.getBestCmap()
    lines = ["// Generated by tools/bake_distribution_glyphs.py; do not edit.",
             "// ClassWizMathCW 1.003, SIL OFL 1.1; licenses/OFL-ClassWiz-fonts.txt.",
             f"// Source SHA256: {FONT_SHA256}",
             "#pragma once", '#include <Adafruit_GFX.h>',
             "namespace Calculator { namespace DistributionGlyphs {"]
    for name, cp in (("Mu", 0x1D707), ("Sigma", 0x1D70E), ("Lambda", 0x1D706)):
        glyph = cmap[cp]
        rows, x, y, _, _ = raster(glyphs, glyph)
        # GFX drawBitmap uses byte-aligned rows.
        data = []
        for row in rows:
            for start in range(0, len(row), 8):
                data.append(sum(int(bit) << (7 - i) for i, bit in enumerate(row[start:start + 8])))
        lines += [f"constexpr uint8_t k{name}[] = {{" + ', '.join(f'0x{b:02x}' for b in data) + "};",
                  f"inline void draw{name}(GFXcanvas1& c, int16_t x, int16_t baseline, uint16_t ink) {{",
                  f"  c.drawBitmap(x + {x}, baseline + {y}, k{name}, {len(rows[0])}, {len(rows)}, ink);", "}"]
    lines += ["} }", ""]
    dest = Path(__file__).resolve().parents[2] / 'src/calculator/assets/calculator_distribution_glyphs.h'
    dest.write_text('\n'.join(lines), encoding='utf-8')
    print(dest)


if __name__ == '__main__':
    main()
