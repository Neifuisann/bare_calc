"""Import the manual's 47 constants from NIST's 2022 CODATA table.

Input: https://physics.nist.gov/cuu/Constants/Table/allascii.txt
Exact repeating values use defining expressions, not truncated NIST ellipses.
"""
import argparse
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('table',type=Path);args=p.parse_args()
content=args.table.read_text()
assert '2022 CODATA adjustment' in content
table={line[:60].strip():line[60:85].strip().replace(' ','').replace('e','E') for line in content.splitlines()[10:]}
groups=[('Universal',[
 ('h','Planck constant'),('hbar','=6.62607015E-34/(2*pi)'),('c','speed of light in vacuum'),
 ('epsilon0','vacuum electric permittivity'),('mu0','vacuum mag. permeability'),('Z0','characteristic impedance of vacuum'),
 ('G','Newtonian constant of gravitation'),('lP','Planck length'),('tP','Planck time')]),
 ('Electromagnetic',[
 ('muN','nuclear magneton'),('muB','Bohr magneton'),('e','elementary charge'),('Phi0','=6.62607015E-34/(2*1.602176634E-19)'),
 ('G0','=2*(1.602176634E-19)^2/6.62607015E-34'),('KJ','=2*1.602176634E-19/6.62607015E-34'),('RK','=6.62607015E-34/(1.602176634E-19)^2')]),
 ('Atomic & Nuclear',[
 ('mp','proton mass'),('mn','neutron mass'),('me','electron mass'),('mmu','muon mass'),('a0','Bohr radius'),
 ('alpha','fine-structure constant'),('re','classical electron radius'),('lambdaC','Compton wavelength'),('gammaP','proton gyromag. ratio'),
 ('lambdaCp','proton Compton wavelength'),('lambdaCn','neutron Compton wavelength'),('Rinf','Rydberg constant'),
 ('mup','proton mag. mom.'),('mue','electron mag. mom.'),('mun','neutron mag. mom.'),('mumu','muon mag. mom.'),('mtau','tau mass')]),
 ('Physico-Chem',[
 ('mu','atomic mass constant'),('F','=6.02214076E23*1.602176634E-19'),('NA','Avogadro constant'),('k','Boltzmann constant'),
 ('Vm','=6.02214076E23*1.380649E-23*273.15/101325'),('R','=6.02214076E23*1.380649E-23'),
 ('c1','=2*pi*6.62607015E-34*(299792458)^2'),('c2','=6.62607015E-34*299792458/1.380649E-23'),
 ('sigma','=2*pi^5/15*(1.380649E-23/6.62607015E-34)^3*1.380649E-23/(299792458)^2')]),
 ('Adopted Values', [('gn','standard acceleration of gravity'),('atm','standard atmosphere'),
 ('RK-90','conventional value of von Klitzing constant'),('KJ-90','conventional value of Josephson constant')]),
 ('Other',[('t','=273.15')])]
lines=['#pragma once','namespace Calculator {','struct ConstantEntry {const char* group;const char* label;const char* expression;};',
       '// NIST 2022 CODATA. Generated by tools/generate_calculator_constants.py.',
       'inline constexpr ConstantEntry kConstants[] = {']
for group,entries in groups:
    for label,name in entries:
        value=name[1:] if name.startswith('=') else table[name]
        assert value and '...' not in value,(name,value)
        lines.append('  {"'+group+'","'+label+'","'+value+'"},')
assert sum(len(g[1]) for g in groups)==47
lines+=['};','} // namespace Calculator','']
(Path(__file__).resolve().parents[2]/'src/calculator/assets/calculator_constants.h').write_text('\n'.join(lines),encoding='ascii')
