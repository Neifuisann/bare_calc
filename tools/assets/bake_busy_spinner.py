#!/usr/bin/env python3
"""Bake the fx-991CN CW busy spinner BMP into src/calculator/assets/calculator_busy.h.

The source is a small 4-bit uncompressed BMP (white + three ink greys, tight
crop). Palette indices are ordered by luminance, so white maps to GrayCanvas
level 0 and the three inks to levels 1..3. Masks are MSB-first rows padded to
a byte, matching GrayCanvas::bits(). Geometry (kW/kH/kX/kY) comes from the
BMP dimensions, centered on the 192x63 panel.

Usage:
    python tools/assets/bake_busy_spinner.py <input.bmp> <output.h>
"""

import struct
import sys
from pathlib import Path

PANEL_W, PANEL_H = 192, 63


def load_levels(path: Path) -> tuple[list[list[int]], int, int]:
    """Return (rows[y][x] of GrayCanvas level 0..3 top-down, width, height)."""
    data = path.read_bytes()
    if data[:2] != b"BM":
        raise ValueError(f"{path}: not a BMP")
    pixel_offset = struct.unpack_from("<I", data, 10)[0]
    header_size = struct.unpack_from("<I", data, 14)[0]
    width, height = struct.unpack_from("<ii", data, 18)
    bpp, compression = struct.unpack_from("<H", data, 28)[0], struct.unpack_from("<I", data, 30)[0]
    if bpp != 4 or compression != 0:
        raise ValueError(f"{path}: need uncompressed 4-bit BMP (got {bpp}bpp, compression {compression})")
    if width <= 0 or width > PANEL_W or abs(height) <= 0 or abs(height) > PANEL_H:
        raise ValueError(f"{path}: need dimensions within {PANEL_W}x{PANEL_H} (got {width}x{height})")
    width, height = width, abs(height)
    palette = data[14 + header_size:pixel_offset]
    luminance = [(palette[i + 2] * 299 + palette[i + 1] * 587 + palette[i] * 114) // 1000
                 for i in range(0, len(palette), 4)]
    stride = ((width * bpp + 31) // 32) * 4
    bottom_up = struct.unpack_from("<i", data, 18)[0] > 0
    indices = []
    for row in range(height):
        src = (height - 1 - row) if bottom_up else row
        base = pixel_offset + src * stride
        for x in range(width):
            byte = data[base + (x >> 1)]
            indices.append((byte >> 4) & 0xF if x % 2 == 0 else byte & 0xF)
    # Brightest used entry is white (level 0); inks follow in order.
    used = sorted(set(indices), key=lambda i: -luminance[i])
    if len(used) != 4:
        raise ValueError(f"{path}: need white + three inks (got {len(used)} colors)")
    level_of = {index: level for level, index in enumerate(used)}
    rows = [[level_of[i] for i in indices[y * width:(y + 1) * width]] for y in range(height)]
    return rows, width, height


def mask(rows: list[list[int]], width: int, height: int, level: int) -> bytes:
    stride = (width + 7) // 8
    out = bytearray(stride * height)
    for y in range(height):
        for x in range(width):
            if rows[y][x] == level:
                out[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out)


def emit(name: str, data: bytes) -> str:
    lines = [f"constexpr uint8_t {name}[{len(data)}] = {{"]
    for offset in range(0, len(data), 6):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[offset:offset + 6]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    rows, width, height = load_levels(source)
    kx, ky = (PANEL_W - width) // 2, (PANEL_H - height) // 2
    counts = [sum(cell == level for row in rows for cell in row) for level in (1, 2, 3)]
    header = f"""#pragma once
#include <cstdint>
#include <vector>

// Centered busy spinner, baked from the fx-991CN CW capture {source.name}
// ({width}x{height}, 4-bit: white + three ink greys, tight crop, no padding). The
// original shows this one static frame while a calculation runs -- no text,
// no animation -- so the firmware paints it as a modal takeover while
// jobs.running() with no notice of its own. Generated by
// tools/bake_busy_spinner.py from {source.name}; do not edit by hand.
namespace Calculator {{
namespace Busy {{
constexpr int16_t kW = {width}, kH = {height};
// Centered on the {PANEL_W}x{PANEL_H} panel: ({PANEL_W}-{width})/2, ({PANEL_H}-{height})/2, truncated.
constexpr int16_t kX = {kx}, kY = {ky};
{emit("kBlack", mask(rows, width, height, 3))}
{emit("kDark", mask(rows, width, height, 2))}
{emit("kLight", mask(rows, width, height, 1))}
// Blank screen + spinner at (kX, kY); levels follow GrayCanvas (0 white).
std::vector<uint8_t> renderBusy();
}}  // namespace Busy
}}  // namespace Calculator
"""
    output.write_text(header, encoding="utf-8")
    print(f"{output}: {width}x{height} at ({kx},{ky}), levels 1/2/3 pixels = {counts[0]}/{counts[1]}/{counts[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
